import { expect, test } from "vitest";
import { describeInferenceSource, resolveInferenceMode } from "./ai-policy.js";

test("una cuenta premium puede recurrir a la nube", () => {
	expect(resolveInferenceMode({ cloudEnabled: true, premium: true })).toBe(
		"prefer_on_device",
	);
});

test("sin premium se queda en el dispositivo aunque la nube esté abierta", () => {
	// Es la diferencia entre "no disponible" y una factura inesperada.
	expect(resolveInferenceMode({ cloudEnabled: true, premium: false })).toBe(
		"only_on_device",
	);
});

test("el interruptor global manda sobre el premium", () => {
	expect(resolveInferenceMode({ cloudEnabled: false, premium: true })).toBe(
		"only_on_device",
	);
});

test("por defecto nadie gasta: sin nube ni premium, sólo dispositivo", () => {
	expect(resolveInferenceMode({ cloudEnabled: false, premium: false })).toBe(
		"only_on_device",
	);
});

test("describe dónde se resolvió la generación", () => {
	expect(describeInferenceSource("on_device")).toBe("Generated on your device");
	expect(describeInferenceSource("in_cloud")).toBe("Generated in the cloud");
});

test("si el SDK no lo informa, no se inventa la procedencia", () => {
	expect(describeInferenceSource(undefined)).toBe("Generated by AI");
});
