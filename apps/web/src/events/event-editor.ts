	@state() private aiBlockDismissed = false;

	/** Lazy: building it doesn't call the model on its own. */
	#tagSuggestionSession: ReturnType<typeof createAiModelSession> | undefined;

	/**
	 * The pattern `ai-event-generator.ts` used to reuse before it stopped
	 * being a reusable instance (it's now recreated on every mount, so it
	 * tracks disposal with a plain `#disposed` boolean instead): this editor
	 * is still a single instance reused across events —`events-view.ts`
	 * toggles `.open`/`.event`/`.draft` on the same element, never
	 * unmounting it—, so a suggestion requested for one event must not
	 * apply if, while the model was thinking, the editor closed and
	 * reopened for another. A review found exactly this kind of bug in the
	 * earlier design —the two-phase save gate— before this button replaced
	 * it.
	 */
	#tagGeneration = 0;

	override willUpdate(changed: Map<string, unknown>): void {
		// On opening, the form starts from what's being edited or from what
		// the AI proposed. Without this the dialog would keep the previous
		// values.
		//
		// Also when the event or the draft changes with the dialog already
		// open. Today there's no path that triggers this —`editing` and
		// `draft` are only touched on open and on close— so it doesn't fix
		// any live bug; it closes off the trap where whichever appears first
		// reopens the editor with the previous event's tags and no warning.
		if (
			(changed.has("open") || changed.has("event") || changed.has("draft")) &&
			this.open
		) {
			this.imageUrl = this.draft?.imageUrl ?? this.event?.imageUrl ?? "";
			this.tags = normalizeTags(this.draft?.tags ?? this.event?.tags ?? []);
			this.tagDraft = "";
			this.error = "";
			this.progress = 0;
			this.aiSuggestedTags = [];
			this.suggestingTags = false;
			this.tagSuggestionDownloading = false;
			this.tagSuggestionProgress = 0;
			this.aiBlockDismissed = false;
			// Counts as a close: a suggestion requested before reopening —for
			// the same event or for another— must not apply when it resolves.
			this.#tagGeneration++;
			void this.#refreshAiAvailability();
		}
	}

	/**
	 * Whether to offer the embedded "fill in with AI" block: only when
	 * creating (never editing), only before anything's been generated or
	 * written by hand —a `draft` already means there's something to review,
	 * whether it came from a real generation or from T33's sample event—,
	 * only with AI available, and not after an explicit "Write it by hand".
	 */
	get #showAiBlock(): boolean {
		return (
			this.event === undefined &&
			this.draft === undefined &&
			this.aiAvailable &&
			!this.aiBlockDismissed
		);
	}

	/**
	 * Whether it's worth offering the button. Checked on every open, not
	 * just once: the model's state can change between one open and the
	 * next —a download that finishes, for example—.
	 */
	async #refreshAiAvailability(): Promise<void> {
		this.aiAvailable = canOffer(await checkAvailability());
	}

