import {
	eventRepositoryContext,
	imageStoreContext,
	userContext,
} from "../application/context.js";
import {
	type AiModelPort,
	aiModelContext,
} from "../application/ports/ai-model.js";
import {
	type AnalyticsPort,
	analyticsContext,
	noopAnalytics,
} from "../application/ports/analytics.js";
import type { EventRepositoryPort } from "../application/ports/event-repository.js";
import type { ImageStorePort } from "../application/ports/image-store.js";
import type { SessionUser } from "../application/ports/session.js";
import { saveEvent } from "../application/save-event.js";
import { canOffer, checkAvailability } from "../domain/ai-availability.js";
import {
	describeInferenceSource,
	type InferenceSourceName,
} from "../domain/ai-policy.js";
import { fromDateFields, toDateFields } from "../domain/date-fields.js";
import {
	eventSchema,
	type PlanuEvent,
	type StoredEvent,
} from "../lib/types.js";
import { typographyStyles } from "../styles/typography.js";
import type { GeneratedDraft } from "./ai-event-generator.js";
import { CoverField, coverFieldStyles } from "./cover-field.js";
import { TagField, tagFieldStyles } from "./tag-field.js";
import { tagChipStyles } from "./tag-styles.js";
import { TagSuggestionController } from "./tag-suggestion-controller.js";

@customElement("planu-event-editor")
export class PlanuEventEditor extends LitElement {
	static override styles = [
		typographyStyles,
		tagChipStyles,
		tagFieldStyles,
		coverFieldStyles,
		css`
		form {
			display: flex;
			flex-direction: column;
			gap: var(--wa-space-m);
		}

		.dates {
			display: flex;
			flex-wrap: wrap;
			gap: var(--wa-space-m);
		}

		.dates > * {
			flex: 1 1 10rem;
		}
		`,
	];

	@property({ type: Boolean }) open = false;

	/** Present in edit mode. */
	@property({ attribute: false }) event: StoredEvent | undefined;

	/** Values proposed by the AI to prefill a new event. */
	@property({ attribute: false }) draft: Partial<PlanuEvent> | undefined;

	/** Where the generation resolved, to tell the user about it. */
	@property({ attribute: false }) draftSource: InferenceSourceName | undefined;

	/**
	 * Whether `draft` is T33's sample event and not something the AI
	 * proposed.
	 *
	 * Not inferred from `draftSource === undefined`: that value already
	 * meant "it was generated, but where isn't known" (see
	 * `describeInferenceSource`), and reusing it here would have made the
	 * sample announce itself as "Generated by AI", which is simply false.
	 */
	@property({ type: Boolean }) isSample = false;

	/**
	 * Whether the account has no events yet, so creating one now is its
	 * first (T31's `first_event_created`). Decided by the view from the
	 * listing it already holds, not by a count on every save (GH-94).
	 * Biased on purpose: while that listing is loading or errored this stays
	 * false, so no signal is sent rather than a false one.
	 */
	@property({ type: Boolean }) isFirstEvent = false;

	@consume({ context: aiModelContext, subscribe: true })
	private aiModel: AiModelPort | undefined;

	@consume({ context: eventRepositoryContext, subscribe: true })
	private eventRepository: EventRepositoryPort | undefined;

	@consume({ context: imageStoreContext, subscribe: true })
	private imageStore: ImageStorePort | undefined;

	@consume({ context: userContext, subscribe: true })
	private user: SessionUser | null | undefined;

	@consume({ context: analyticsContext, subscribe: true })
	private analytics: AnalyticsPort = noopAnalytics;

	@state() private saving = false;
	@state() private error = "";

	private readonly tagField = new TagField(this, {
		getError: () => this.error,
		setError: (message) => {
			this.error = message;
		},
	});

	private readonly coverField = new CoverField(this, {
		getImageStore: () => this.imageStore,
		getUser: () => this.user,
		setError: (message) => {
			this.error = message;
		},
	});

	/** The ones the user already uses in other events, for autocomplete. */
	@property({ attribute: false }) knownTags: readonly string[] = [];

	/** "Suggest tags with AI" (T24). Not `#private` so tests can seed it. */
	private readonly tagSuggestions = new TagSuggestionController(this, {
		getAiModel: () => this.aiModel,
		getUser: () => this.user,
	});

	/**
	 * Whether it's worth showing the button. Same as `aiAvailable` in
	 * `events-view.ts`: a button that would always fail is worse than a
	 * button that isn't there, so it isn't offered with `unavailable` or
	 * without the browser API.
	 */
	@state() private aiAvailable = false;

	/**
	 * Whether "Write it by hand" was clicked on the embedded AI block for the
	 * event currently being created. Reset on every open (see
	 * `willUpdate()`): the point is to let this one attempt drop back to the
	 * empty form, not to remember the choice across a whole session.
	 */
	@state() private aiBlockDismissed = false;

	override willUpdate(changed: Map<string, unknown>): void {
		// On opening, the form starts from what's being edited or from what
		// the AI proposed. Without this the dialog would keep the previous
		// values.
		//
		// Also when the event or the draft changes with the dialog already
		// open. Today there's no path that triggers this —`editing` and
		// `draft` are only touched on open and on close— so it doesn't fix
		// any live bug; it closes off the trap where whichever appears first
		// reopens the editor with the previous event's tags and no warning.
		if (
			(changed.has("open") || changed.has("event") || changed.has("draft")) &&
			this.open
		) {
			this.coverField.reset(this.draft?.imageUrl ?? this.event?.imageUrl ?? "");
			this.tagField.reset(this.draft?.tags ?? this.event?.tags ?? []);
			this.error = "";
			this.aiBlockDismissed = false;
			// Counts as a close: a suggestion requested before reopening —for
			// the same event or for another— must not apply when it resolves.
			this.tagSuggestions.reset();
			void this.#refreshAiAvailability();
		}
	}

	/**
	 * Whether to offer the embedded "fill in with AI" block: only when
	 * creating (never editing), only before anything's been generated or
	 * written by hand —a `draft` already means there's something to review,
	 * whether it came from a real generation or from T33's sample event—,
	 * only with AI available, and not after an explicit "Write it by hand".
	 */
	get #showAiBlock(): boolean {
		return (
			this.event === undefined &&
			this.draft === undefined &&
			this.aiAvailable &&
			!this.aiBlockDismissed
		);
	}

	/**
	 * Whether it's worth offering the button. Checked on every open, not
	 * just once: the model's state can change between one open and the
	 * next —a download that finishes, for example—.
	 */
	async #refreshAiAvailability(): Promise<void> {
		this.aiAvailable = canOffer(await checkAvailability());
	}

	override render() {
		const initial = { ...this.event, ...this.draft };
		const editing = this.event !== undefined;

		return html`
			<wa-dialog
				label=${editing ? msg("Edit event") : msg("New event")}
				.open=${this.open}
				@wa-hide=${this.#close}
			>
				${
					this.error
						? html`<wa-callout variant="danger" role="alert">${this.error}</wa-callout>`
						: nothing
				}

				${
					this.draft && this.open
						? html`<wa-callout variant="neutral">
								${
									this.isSample
										? msg(
												"This is a sample event. Change anything you like, then save it.",
											)
										: html`${describeInferenceSource(this.draftSource)}.
											${msg("Review the details before saving.")}`
								}
							</wa-callout>`
						: nothing
				}

				${this.open ? this.#renderForm(initial) : nothing}

				<wa-button slot="footer" appearance="outlined" @click=${this.#close}>
					${msg("Cancel")}
				</wa-button>
				<wa-button
					slot="footer"
					variant="brand"
					type="submit"
					form="event-form"
					?disabled=${this.saving || this.coverField.uploading}
				>
					${this.saving ? msg("Saving…") : msg("Save event")}
				</wa-button>
			</wa-dialog>
		`;
	}

	/**
	 * The form is created anew on every open.
	 *
	 * Lit only rewrites a property when it changes relative to what it
	 * committed, and it has no idea what the user is typing. Keeping the
	 * form in the DOM, reopening the editor would show the previous
	 * event's values.
	 */
	#renderForm(initial: Partial<PlanuEvent>) {
		const dates = toDateFields(initial);
		return html`
			<form id="event-form" @submit=${this.#onSubmit}>
					${
						this.#showAiBlock
							? html`
									<planu-ai-event-generator
										@planu-event-generated=${this.#onAiGenerated}
										@planu-generator-dismiss=${this.#onAiDismiss}
									></planu-ai-event-generator>
									<wa-divider></wa-divider>
								`
							: nothing
					}
					${this.coverField.render()}

					<wa-input
						name="title"
						label=${msg("Title")}
						required
						minlength="3"
						enterkeyhint="next"
						.value=${initial.title ?? ""}
					></wa-input>

					<wa-textarea
						name="description"
						label=${msg("Description")}
						.value=${initial.description ?? ""}
					></wa-textarea>

					<wa-input
						name="location"
						label=${msg("Location")}
						enterkeyhint="next"
						.value=${initial.location ?? ""}
					></wa-input>

					${this.tagField.render(this.knownTags, (full) =>
						this.tagSuggestions.render({
							available: this.aiAvailable,
							full,
							onSuggest: () => void this.#onSuggestTags(),
							onAccept: (tag) => this.#addAiSuggestedTag(tag),
						}),
					)}

					<div class="dates">
						<wa-input
							type="date"
							name="startDate"
							label=${msg("Start date")}
							.value=${dates.startDate}
						></wa-input>
						<wa-input
							type="time"
							name="startTime"
							label=${msg("Start time")}
							.value=${dates.startTime}
						></wa-input>
						<wa-input
							type="date"
							name="endDate"
							label=${msg("End date")}
							.value=${dates.endDate}
						></wa-input>
						<wa-input
							type="time"
							name="endTime"
							label=${msg("End time")}
							enterkeyhint="done"
							.value=${dates.endTime}
						></wa-input>
					</div>
				</form>
		`;
	}

	/**
	 * The AI block generated something: it's handed off exactly like a
	 * `draft` set from outside always was —`#showAiBlock` hides the block on
	 * its own once `draft` stops being `undefined`, no separate signal to
	 * close it is needed.
	 */
	async #onAiGenerated(domEvent: Event): Promise<void> {
		const { event, source } = (domEvent as CustomEvent<GeneratedDraft>).detail;
		this.draft = event;
		this.draftSource = source;
		await this.#focusTitle();
	}

	/** "Write it by hand": the block goes away without anything generated. */
	async #onAiDismiss(): Promise<void> {
		this.aiBlockDismissed = true;
		await this.#focusTitle();
	}

	/**
	 * Moves focus to the title field. Called after the AI block disappears
	 * —generated or dismissed—, because the control that had focus just left
	 * the DOM with it: without this, focus falls back to `<body>`, a real
	 * keyboard-navigation regression that static axe analysis alone doesn't
	 * catch.
	 */
	async #focusTitle(): Promise<void> {
		await this.updateComplete;
		this.shadowRoot
			?.querySelector<HTMLElement & { focus: () => void }>('[name="title"]')
			?.focus();
	}

	#addAiSuggestedTag(tag: string): void {
		this.tagField.add(tag);
		// It doesn't disappear from winning one: if the AI proposed three,
		// accepting the first one shouldn't force repeating the save to get
		// to the second.
		this.tagSuggestions.accept(tag);
	}

	async #onSubmit(domEvent: SubmitEvent): Promise<void> {
		domEvent.preventDefault();

		const { eventRepository, user } = this;
		if (!eventRepository || !user) return;

		const data = new FormData(domEvent.target as HTMLFormElement);
		const text = (key: string) => String(data.get(key) ?? "").trim();
		const { startDate, endDate, allDay } = fromDateFields({
			startDate: text("startDate"),
			startTime: text("startTime"),
			endDate: text("endDate"),
			endTime: text("endTime"),
		});

		const parsed = eventSchema().safeParse({
			title: text("title"),
			description: text("description"),
			location: text("location"),
			startDate,
			endDate,
			allDay,
			imageUrl: this.coverField.imageUrl,
			userId: user.uid,
			tags: this.tagField.tags,
		});

		if (!parsed.success) {
			this.error = parsed.error.issues[0]?.message ?? msg("Check the form.");
			return;
		}

		this.saving = true;
		try {
			await saveEvent(eventRepository, this.analytics, {
				values: parsed.data,
				ownerUid: user.uid,
				editingId: this.event?.id,
				isFirstEvent: () => this.isFirstEvent,
			});
			this.#close();
		} catch {
			this.error = msg("The event could not be saved. Please try again.");
		} finally {
			this.saving = false;
		}
	}

	/**
	 * Reads a form field exactly as it's written right now, without
	 * waiting for submission. The form is uncontrolled —it's read with
	 * `FormData` on save—, so the button needs its own path to the DOM to
	 * know what's written at this instant.
	 */
	#fieldValue(name: string): string {
		const field = this.shadowRoot?.querySelector<
			HTMLElement & { value?: string }
		>(`[name="${name}"]`);
		return (field?.value ?? "").trim();
	}

	/**
	 * Asks the AI for up to three tags with whatever is written right now.
	 * It's an explicit button and not something automatic on typing
	 * —Title, description and location aren't wired to reactive state, so
	 * firing this on every keystroke would have also required a
	 * `debounce` with cancellation of the previous call— and it doesn't
	 * depend on saving either: it can be requested, ignored and saved
	 * without any, just like before this button existed.
	 */
	#onSuggestTags(): Promise<void> {
		return this.tagSuggestions.suggest(() => ({
			title: this.#fieldValue("title"),
			description: this.#fieldValue("description"),
			location: this.#fieldValue("location"),
			knownTags: this.knownTags,
			chosenTags: this.tagField.tags,
		}));
	}

	#close(): void {
		// Closing invalidates any suggestion that was still thinking.
		this.tagSuggestions.invalidate();
		this.open = false;
		// This instance is never unmounted, and the parent's own binding on
		// `.draft`/`.draftSource` only ever changes when it goes from one
		// concrete value to another — going from `undefined` to `undefined`
		// (the common case: the parent's state was never set in the first
		// place) never re-invokes the property setter, because lit-html's
		// dirty-check compares against the *expression's* last committed
		// value, not against this element's actual current property. Since
		// `#onAiGenerated` writes `this.draft` directly (bypassing that
		// binding), a generated draft would otherwise survive forever across
		// "New event" openings once written — clearing it here, on our own
		// close, is what guarantees a blank form next time regardless of what
		// the parent's binding does.
		this.draft = undefined;
		this.draftSource = undefined;
		this.dispatchEvent(new CustomEvent("planu-editor-close"));
	}
}

